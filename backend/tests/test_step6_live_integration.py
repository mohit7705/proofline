"""Opt-in live PostgreSQL + real FFmpeg integration test for Step 6."""

import asyncio
import hashlib
import os
import subprocess
import tempfile
import uuid
from pathlib import Path

import pytest
from dotenv import dotenv_values
from sqlalchemy import URL, create_engine
from sqlalchemy.orm import Session


def test_step6_real_database_and_video(monkeypatch):
    if os.getenv("PROOFLINE_LIVE_DB_TEST") != "1":
        pytest.skip("Set PROOFLINE_LIVE_DB_TEST=1 to run live integration test")

    root = Path(__file__).resolve().parents[2]
    env = dotenv_values(root / ".env")

    db_url = URL.create(
        "postgresql+psycopg",
        username=env.get("POSTGRES_USER") or "proofline",
        password=env.get("POSTGRES_PASSWORD") or "proofline_local_dev_2026",
        host="127.0.0.1",
        port=5433,
        database=env.get("POSTGRES_DB") or "proofline",
    )

    monkeypatch.setenv("DATABASE_URL", db_url.render_as_string(hide_password=False))

    engine = create_engine(db_url, pool_pre_ping=True)
    session = Session(engine)

    user_id = work_order_id = task_id = evidence_id = None
    storage = None

    try:
        with engine.connect() as conn:
            assert conn.exec_driver_sql("SELECT 1").scalar_one() == 1
        print("\nPASS: PostgreSQL connection")

        from app.models import Evidence, Task, User, VerificationRun, WorkOrder
        from app.schemas.video_analysis import VideoAnalysisResult
        from app.services import video_verification

        storage = tempfile.TemporaryDirectory(prefix="proofline-step6-")
        storage_dir = Path(storage.name)
        video_path = storage_dir / "step6-integration.mp4"

        subprocess.run(
            [
                "ffmpeg", "-hide_banner", "-loglevel", "error",
                "-nostdin", "-y",
                "-f", "lavfi", "-i", "color=c=blue:s=320x240:r=10",
                "-t", "3", "-pix_fmt", "yuv420p", str(video_path),
            ],
            check=True,
            timeout=30,
        )
        assert video_path.is_file() and video_path.stat().st_size > 0
        monkeypatch.setenv("EVIDENCE_STORAGE_DIR", str(storage_dir))
        print("PASS: Real MP4 generated by FFmpeg")

        token = uuid.uuid4().hex
        user = User(
            email=f"step6-{token}@example.invalid",
            full_name="Step 6 Integration Test",
            role="manager",
            is_active=True,
        )
        session.add(user)
        session.flush()
        user_id = user.id

        work_order = WorkOrder(
            title=f"Step 6 integration {token[:8]}",
            description="Temporary automated integration test",
            created_by=user.id,
            status="open",
        )
        session.add(work_order)
        session.flush()
        work_order_id = work_order.id

        task = Task(
            work_order_id=work_order.id,
            title="Inspect generated video",
            instructions="Inspect the supplied video evidence.",
            status="submitted",
            position=0,
        )
        session.add(task)
        session.flush()
        task_id = task.id

        content = video_path.read_bytes()
        evidence = Evidence(
            task_id=task.id,
            submitted_by=user.id,
            media_type="video",
            storage_key=video_path.name,
            original_filename=video_path.name,
            content_type="video/mp4",
            media_metadata={"duration_seconds": 3.0},
            size_bytes=len(content),
            sha256_hash=hashlib.sha256(content).hexdigest(),
            integrity_status="pending",
        )
        session.add(evidence)
        session.commit()
        session.refresh(evidence)
        evidence_id = evidence.id
        print("PASS: Isolated test records persisted")

        async def fake_model_analysis(**kwargs):
            # Only AI is mocked. The real evidence and frame pipeline runs.
            frames = kwargs["frames"]
            assert len(frames) == 1
            assert frames[0].image_bytes.startswith(b"\xff\xd8\xff")
            assert frames[0].timestamp_seconds == 1.0

            return VideoAnalysisResult(
                status="completed",
                observations=[],
                confidence=0.91,
                flags=[],
                coverage={
                    "video_duration_seconds": 3.0,
                    "sampled_timestamps_seconds": [1.0],
                    "sampling_strategy": "manual",
                },
            )

        monkeypatch.setattr(
            video_verification, "analyze_video_frames", fake_model_analysis
        )

        run = asyncio.run(
            video_verification.verify_video_evidence(
                db=session,
                evidence_id=evidence.id,
                user=user,
                timestamps_seconds=[1.0],
            )
        )

        session.refresh(evidence)
        session.refresh(run)

        assert evidence.integrity_status == "passed"
        assert run.status == "completed"
        assert run.confidence == pytest.approx(0.91)
        assert run.findings["status"] == "completed"
        assert run.findings["flags"] == []
        assert run.findings["coverage"]["sampled_timestamps_seconds"] == [1.0]
        assert run.completed_at is not None

        # Confirm persisted data by reloading the run from PostgreSQL.
        persisted = session.get(VerificationRun, run.id)
        assert persisted is not None
        assert persisted.status == "completed"
        assert persisted.confidence == pytest.approx(0.91)

        print("PASS: SHA-256 integrity verification")
        print("PASS: Real FFmpeg JPEG frame extraction")
        print("PASS: VerificationRun and confidence persisted in PostgreSQL")
        print("RESULT: STEP 6 LIVE MEDIA/DATABASE INTEGRATION PASSED")
        print("NOTE: AI provider itself was mocked, not called live.")

    finally:
        # Delete only records created by this test, in FK dependency order.
        try:
            session.rollback()
            if evidence_id is not None:
                session.query(VerificationRun).filter(
                    VerificationRun.evidence_id == evidence_id
                ).delete(synchronize_session=False)
                session.query(Evidence).filter(
                    Evidence.id == evidence_id
                ).delete(synchronize_session=False)
            if task_id is not None:
                session.query(Task).filter(Task.id == task_id).delete(
                    synchronize_session=False
                )
            if work_order_id is not None:
                session.query(WorkOrder).filter(
                    WorkOrder.id == work_order_id
                ).delete(synchronize_session=False)
            if user_id is not None:
                session.query(User).filter(User.id == user_id).delete(
                    synchronize_session=False
                )
            session.commit()
            print("Cleanup: test database records removed")
        except Exception as cleanup_error:  # noqa: BLE001
            session.rollback()
            print(f"WARNING: Test cleanup failed: {cleanup_error}")
        finally:
            session.close()
            engine.dispose()
            if storage is not None:
                storage.cleanup()
